function generateMockHistory(basePrice: number, volatilityPct: number = 2.2): HistoricalBar[] {
  const bars: HistoricalBar[] = [];
  const totalDays = 180;
  const now = new Date();

  // Start from basePrice * 0.88 180 days ago and trend towards basePrice
  let p = Number((basePrice * 0.88).toFixed(2));

  for (let i = totalDays; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dayOfWeek = d.getDay();
    if (dayOfWeek === 0 || dayOfWeek === 6) continue; // Pomiń weekendy

    const progress = (totalDays - i) / totalDays;
    const trendTarget = basePrice * (0.88 + 0.12 * Math.pow(progress, 0.85));
    const wave = Math.sin(i / 5) * (basePrice * 0.025);

    const open = p;

    // Daily move: deterministic calculation based on day index and basePrice
    const pseudo = Math.sin(basePrice * 17.3 + i * 29.7) * 0.5 + 0.5;
    const dailySwing = (pseudo - 0.47) * (basePrice * (volatilityPct / 100));
    const trendPull = (trendTarget + wave - open) * 0.18;
    let close = i === 0 ? basePrice : Number((open + dailySwing + trendPull).toFixed(2));
    close = Math.max(0.1, close);

    // Body size
    const bodySize = Math.abs(close - open);
    const wickBase = Math.max(basePrice * 0.006, bodySize * 0.35);

    // High & Low wicks proportional to body
    const wickP = Math.sin(basePrice * 31.1 + i * 43.3) * 0.5 + 0.5;
    const topWick = Number((wickP * wickBase).toFixed(2));
    const bottomWick = Number(((1 - wickP) * wickBase).toFixed(2));

    const high = Number((Math.max(open, close) + topWick).toFixed(2));
    const low = Number((Math.max(0.01, Math.min(open, close) - bottomWick)).toFixed(2));
    const volume = Math.floor(pseudo * 500000) + 50000;

    bars.push({
      date: d.toISOString().split('T')[0],
      open: Number(open.toFixed(2)),
      high,
      low,
      close,
      volume
    });

    p = close;
  }

  return bars;
}

